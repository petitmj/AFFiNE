import type { ShelfPalette } from '@affine/core/modules/shelf';
import { SCENE_HEIGHT, SCENE_WIDTH } from '@affine/core/modules/shelf';
import type { ReactElement } from 'react';

import { tonesOf, Wall } from './scene-room';
import { Traced } from './scene-traced';

/** painter's order: bands first, the bookcases last so they stand in front */
const BEHIND = ['strip_l', 'strip_r', 'top', 'floor', 'props', 'rug', 'board'];
const IN_FRONT = ['card', 'eagle', 'cases'];
/** the cloth inside the pin board's frame, deepened toward the palette */
const CLOTH = { x: 185, y: 303, width: 274, height: 159 } as const;

/**
 * Decorative backdrop of the Shelf home: the approved home-page picture
 * traced into vector layers (`scene-trace.ts`, generated by
 * `scripts/shelf-trace`), so it scales cleanly and recolours with the
 * palette. It holds the Ndebele top and floor bands, the side strips, the
 * floating shelf with plant and radio, the rug panel, the pin board, the four
 * bookcases and the eagle on its post. It draws no books and no notes; those
 * are real buttons layered on top (see `books.tsx`), so the art can change
 * without touching behaviour.
 */
export function ShelfScene({ palette }: { palette: ShelfPalette }) {
  const t = tonesOf(palette);
  return (
    <svg
      viewBox={`0 0 ${SCENE_WIDTH} ${SCENE_HEIGHT}`}
      width="100%"
      height="100%"
      aria-hidden="true"
      focusable="false"
      preserveAspectRatio="xMidYMid slice"
      style={{ display: 'block' }}
    >
      <Wall t={t} />
      <Traced t={t} ids={BEHIND} />
      <rect {...CLOTH} fill={t.cloth} fillOpacity="0.5" />
      <Traced t={t} ids={IN_FRONT} />
    </svg>
  ) as ReactElement;
}
